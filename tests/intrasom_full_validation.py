def public_api_members():
    targets = {
        "object_functions": [
            "NeighborhoodFactory",
            "GaussianNeighborhood",
            "BubbleNeighborhood",
            "NormalizerFactory",
            "VarianceNormalizer",
            "NoneNormalizer",
            "WeightedVarianceNormalizer",
        ],
        "codebook": ["Codebook"],
        "intrasom": ["SOMFactory", "SOM"],
        "clustering": ["ClusterFactory"],
        "visualization": ["PlotFactory"],
    }

    found = set()

    for mod_name, class_names in targets.items():
        mod = module(mod_name)
        for cls_name in class_names:
            cls = getattr(mod, cls_name)
            for name, value in cls.__dict__.items():
                if name.startswith("_"):
                    continue
                if isinstance(value, property) or callable(value):
                    found.add(f"{cls_name}.{name}")

    return found


def test_api_coverage():
    public = public_api_members()

    # Normalize module-qualified marks to Class.method form.
    exercised_short = set()
    for item in EXERCISED_API:
        parts = item.split(".")
        if len(parts) >= 2:
            exercised_short.add(".".join(parts[-2:]))

    intentionally_indirect = {
        # Base abstract class methods are not called directly.
        "Normalizer.normalize",
        "Normalizer.normalize_by",
        "Normalizer.denormalize_by",

        # Internal helpers exposed as public in the historical API but exercised
        # through training / geometry workflows.
        "SOM._calculate_ms_and_mpd",
    }

    uncovered = sorted(public - exercised_short - intentionally_indirect)

    print(f"Public API members discovered : {len(public)}")
    print(f"Explicitly exercised          : {len(public) - len(uncovered)}")

    if uncovered:
        print("\nPublic members not explicitly covered by a dedicated call:")
        for item in uncovered:
            print("  -", item)
        RUNNER.warn(
            "Some public members are not explicitly covered. This is not a failure, "
            "but update this suite when new public API is added."
        )
    else:
        print("All discovered public API members are covered.")

    # Save audit for comparison after future updates.
    audit = {
        "public_api": sorted(public),
        "explicitly_marked": sorted(exercised_short),
        "uncovered": uncovered,
    }
    Path("api_coverage_audit.json").write_text(
        json.dumps(audit, indent=2),
        encoding="utf-8",
    )


RUNNER.run("Audit public API coverage", test_api_coverage, critical=False)


