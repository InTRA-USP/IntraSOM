def validate_plotfactory_geometry(plotter, mapsize, lattice):
    cols, rows = mapsize

    # Public helpers.
    rec = plotter.generate_rec_lattice(cols, rows)
    hexa = plotter.generate_hex_lattice(cols, rows)

    require_shape(rec, (rows * cols, 2), "PlotFactory rectangular coordinates")
    require_shape(hexa, (rows * cols, 2), "PlotFactory hex coordinates")

    # Historical odd-r geometry: odd rows are shifted +0.5 in x.
    require_close(hexa[0], [0.0, 0.0])
    if rows > 1:
        require_close(
            hexa[cols],
            [0.5, np.sqrt(3.0) / 2.0],
            message="First neuron of the second hex row has wrong position",
        )
    if rows > 2:
        require_close(
            hexa[2 * cols],
            [0.0, np.sqrt(3.0)],
            message="First neuron of the third hex row has wrong position",
        )

    # Polygon orientation must match Matplotlib RegularPolygon historical
    # orientation: point at top/bottom, not at left/right.
    verts = plotter._polygon_vertices(
        np.array([[0.0, 0.0]]),
        "hexa",
        1.0,
    )[0]
    radius = 1.0 / np.sqrt(3.0)
    require_close(
        verts[0],
        [0.0, radius],
        message="Hexagon orientation changed: top vertex is incorrect",
    )

    require_close(rec[0], [0, 0])
    require_close(rec[cols], [0, 1])
    require_close(rec[-1], [cols - 1, rows - 1])

    require(isinstance(plotter.hits_dictionary, dict), "PlotFactory.hits_dictionary must be dict")

    mark(
        "PlotFactory.generate_rec_lattice",
        "PlotFactory.generate_hex_lattice",
        "PlotFactory.hits_dictionary",
    )


