    cols, rows = expected_mapsize
    nnodes = cols * rows

    require(tuple(som.mapsize) == tuple(expected_mapsize), f"mapsize changed: {som.mapsize}")
    require_shape(som.codebook.matrix, (nnodes, COMPLETE_DF.shape[1]), "codebook matrix")
    require(np.isfinite(som.codebook.matrix).all(), "Codebook contains non-finite values")

    bmus = som._bmu[0].astype(int)
    require(bmus.min() >= 0, "Negative BMU index")
    require(bmus.max() < nnodes, "BMU index exceeds map size")

    require(np.isfinite(som.QE), "Quantization error is not finite")
    require(0 <= som.topographic_error <= 1, "Topographic error must lie in [0,1]")

    distance = som._distance_matrix
    require_shape(distance, (nnodes, nnodes), "SOM distance matrix")

    require(
        np.issubdtype(
            distance.dtype,
            np.floating,
        ),
        (
            "SOM distance matrix must use a floating dtype so grid metrics "
            "are not silently truncated."
        ),
    )

    require(
        np.allclose(
            distance,
            distance.T,
            rtol=0,
            atol=1e-12,
        ),
        "SOM distance matrix is not symmetric",
    )

    require(
        np.allclose(
            np.diag(distance),
            0.0,
            rtol=0,
            atol=1e-12,
        ),
        "Distance diagonal is not zero",
    )

    if som.lattice == "rect":

        center_row = rows // 2
        center_col = cols // 2

        # Keep the reference cell away from the right/bottom boundary.
        center_row = min(
            center_row,
            rows - 3,
        )
        center_col = min(
            center_col,
            cols - 3,
        )

        center = (
            center_row * cols
            + center_col
        )

        right = (
            center_row * cols
            + center_col + 1
        )

        diagonal = (
            (center_row + 1) * cols
            + center_col + 1
        )

        two_right = (
            center_row * cols
            + center_col + 2
        )

        require_close(
            distance[center, right],
            1.0,
            rtol=0,
            atol=1e-12,
            message=(
                "Rectangular SOM orthogonal grid distance must equal 1."
            ),
        )

        require_close(
            distance[center, diagonal],
            2.0,
            rtol=0,
            atol=1e-12,
            message=(
                "Rectangular SOM diagonal squared grid distance must equal 2."
            ),
        )

        require_close(
            distance[center, two_right],
            4.0,
            rtol=0,
            atol=1e-12,
            message=(
                "Rectangular SOM two-step squared grid distance must equal 4."
            ),
        )

    neuron_matrix = som.neuron_matrix
    require_shape(neuron_matrix, (nnodes, COMPLETE_DF.shape[1]), "denormalized neuron matrix")

    neurons_df = som.neurons_dataframe
    results_df = som.results_dataframe

    require(neurons_df.shape[0] == nnodes, "neurons_dataframe row count incorrect")
    require(results_df.shape[0] == len(COMPLETE_DF), "results_dataframe row count incorrect")

    # Coordinate columns must obey row-major convention.
    for idx0 in [0, cols - 1, cols, nnodes - 1]:
        row = idx0 // cols
        col = idx0 % cols
        record = neurons_df.iloc[idx0]
        require(int(record["Ret_x"]) == col, f"Ret_x mismatch at node {idx0}")
        require(int(record["Ret_y"]) == row, f"Ret_y mismatch at node {idx0}")

    um_reduced = som.build_umatrix(expanded=False)
    um_expanded = som.build_umatrix(expanded=True)

    require_shape(um_reduced, (rows, cols), "reduced U-Matrix")

    expected_neighbors = 6 if som.lattice == "hexa" else 8
    require_shape(um_expanded, (rows, cols, expected_neighbors), "expanded U-Matrix")

    if som.lattice == "rect":
        # Corrected rectangular expanded U-Matrix includes diagonals:
        # 0=right, 1=down-right, 2=down, 3=down-left,
        # 4=left, 5=up-left, 6=up, 7=up-right.
        if som.mapshape == "toroid":
            require(
                np.isfinite(um_expanded).all(),
                "Toroidal rectangular U-Matrix must contain all 8 neighbor distances",
            )
        elif rows > 2 and cols > 2:
            center = um_expanded[1, 1]
            require(
                np.isfinite(center[[1, 3, 5, 7]]).all(),
                "Rectangular U-Matrix diagonal distances are missing",
            )

    rep = som.rep_sample(save=False)
    require(isinstance(rep, dict), "rep_sample must return a dict")

    # Direct property and method checks.
    require_shape(som.get_data, COMPLETE_DF.shape, "get_data")
    require(len(som.component_names) == COMPLETE_DF.shape[1], "component_names length incorrect")

    denorm = som.denorm_data(som.get_data[:4])
    require_shape(denorm, (4, COMPLETE_DF.shape[1]), "denorm_data")

    mark(
        "SOM.get_data",
        "SOM.component_names",
        "SOM.calculate_map_dist",
        "SOM.neuron_matrix",
        "SOM.neurons_dataframe",
        "SOM.results_dataframe",
        "SOM.denorm_data",
        "SOM.topographic_error",
        "SOM.build_umatrix",
        "SOM.rep_sample",
    )

    return {
        "QE": float(som.QE),
        "TE": float(som.topographic_error),
        "occupied_bmus": int(np.unique(bmus).size),
    }


