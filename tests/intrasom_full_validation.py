def test_missing_data_workflow():
    if not RUN_MISSING_DATA:
        RUNNER.warn("Missing-data tests disabled.")
        return

    som = train_som(
        data=MISSING_DF,
        mapsize=PRIMARY_MAPSIZE,
        lattice="hexa",
        mapshape="toroid",
        normalization="var",
        missing=True,
        mask=MISSING_FLAG,
        name="missing_data",
    )

    require(np.isfinite(som.codebook.matrix).all(), "Missing-data training produced invalid codebook")

    imputed = som.imput_missing(save=False)
    require(imputed is not None, "imput_missing returned None")

    if isinstance(imputed, pd.DataFrame):
        require(imputed.shape == MISSING_DF.shape, "Imputed DataFrame shape mismatch")
        require(
            imputed.isna().sum().sum() == 0,
            "Imputed DataFrame still contains NaNs",
        )
        require(
            imputed.eq(MISSING_FLAG).sum().sum() == 0,
            "Imputed DataFrame still contains -999 flags",
        )
        imputed_arr = imputed.to_numpy(dtype=float)
        display(imputed.head())
    else:
        imputed_arr = np.asarray(imputed, dtype=float)
        require_shape(imputed_arr, MISSING_DF.shape, "imputed array")
        require(
            not np.isnan(imputed_arr).any(),
            "Imputed array still contains NaNs",
        )
        require(
            not np.any(imputed_arr == MISSING_FLAG),
            "Imputed array still contains -999 flags",
        )

    # Imputation may only replace originally missing cells. Observed cells must remain
    # numerically unchanged apart from the method's output rounding tolerance.
    observed_mask = ~ORIGINAL_MISSING_MASK
    require_close(
        imputed_arr[observed_mask],
        MISSING_DF.to_numpy(dtype=float)[observed_mask],
        atol=1e-5,
        rtol=1e-7,
        message="imput_missing changed originally observed values",
    )
    require(
        np.isfinite(
            imputed_arr[ORIGINAL_MISSING_MASK]
        ).all(),
        "Missing cells were not fully imputed",
    )

    require(
        not np.any(
            imputed_arr[ORIGINAL_MISSING_MASK]
            == MISSING_FLAG
        ),
        "At least one originally flagged cell was not imputed.",
    )

    expected_missing_values = (
        COMPLETE_DF
        .to_numpy(dtype=float)[ORIGINAL_MISSING_MASK]
    )

    actual_imputed_values = (
        imputed_arr[ORIGINAL_MISSING_MASK]
    )

    missing_positions = [
        (str(row_name), str(column_name))
        for row_name, row_mask in zip(
            MISSING_DF.index,
            ORIGINAL_MISSING_MASK,
        )
        for column_name, is_missing in zip(
            MISSING_DF.columns,
            row_mask,
        )
        if bool(is_missing)
    ]

    comparison = pd.DataFrame(
        {
            "position": [
                f"{row} / {column}"
                for row, column in missing_positions
            ],
            "expected_complete": expected_missing_values,
            "som_imputed": actual_imputed_values,
            "absolute_error": np.abs(
                expected_missing_values
                - actual_imputed_values
            ),
        }
    )

    print("\nKnown complete values vs SOM imputation:")
    display(comparison)

    projected = make_projection_df(COMPLETE_DF, n=min(20, len(COMPLETE_DF)))
    projection_result = som.project_nan_data(
        projected,
        with_labels=False,
        save=False,
        imput=True,
    )
    require(len(projection_result) == len(projected), "Missing projection length mismatch")

    mark("SOM.imput_missing", "SOM.project_nan_data")


