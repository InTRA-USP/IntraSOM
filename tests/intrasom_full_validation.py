def require(condition: bool, message: str):
    if not bool(condition):
        raise AssertionError(message)


def require_close(a, b, *, rtol=1e-7, atol=1e-9, equal_nan=False, message="Values differ"):
    if not np.allclose(a, b, rtol=rtol, atol=atol, equal_nan=equal_nan):
        raise AssertionError(
            f"{message}\nA={np.asarray(a)}\nB={np.asarray(b)}"
        )


def require_shape(array, expected, name="array"):
    actual = np.asarray(array).shape
    require(
        actual == tuple(expected),
        f"{name} shape is {actual}, expected {tuple(expected)}",
    )


