def module(name: str):
    key = f"module:{name}"
    if key not in CACHE:
        CACHE[key] = importlib.import_module(f"intrasom.{name}")
    return CACHE[key]


def package_dir() -> Path:
    spec = importlib.util.find_spec("intrasom")
    if spec is None:
        raise RuntimeError(
            "Package `intrasom` not found. Activate the environment and run "
            "`python -m pip install -e .` from the repository root."
        )
    if spec.submodule_search_locations:
        return Path(next(iter(spec.submodule_search_locations))).resolve()
    if spec.origin:
        return Path(spec.origin).resolve().parent
    raise RuntimeError("Could not resolve IntraSOM package path.")


def package_version():
    for candidate in ("IntraSOM", "intrasom"):
        try:
            return importlib.metadata.version(candidate)
        except importlib.metadata.PackageNotFoundError:
            pass
    return "<metadata unavailable>"


