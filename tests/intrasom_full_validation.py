def test_grid_distances_all_topologies():
    # Full topology/lattice matrix on a large map with an even row count,
    # so the hexagonal toroid is periodic without automatic size adjustment.
    for mapsize in [PRIMARY_MAPSIZE]:
        cols, rows = mapsize
        nnodes = cols * rows

        print(f"\nMap {mapsize} -> {nnodes} nodes")

        for mapshape in ["planar", "toroid"]:
            for lattice in ["rect", "hexa"]:
                cb = create_codebook(mapsize, lattice=lattice, mapshape=mapshape)

                matrix = np.vstack([
                    cb.grid_dist(i)
                    for i in range(nnodes)
                ])

                require_shape(matrix, (nnodes, nnodes), f"{lattice}/{mapshape} distance matrix")
                require(np.all(np.diag(matrix) == 0), f"Diagonal not zero: {lattice}/{mapshape}")
                require(np.array_equal(matrix, matrix.T), f"Distance matrix not symmetric: {lattice}/{mapshape}")

                zero_offdiag = matrix.copy()
                np.fill_diagonal(zero_offdiag, 1)
                require(np.all(zero_offdiag > 0), f"False zero distances: {lattice}/{mapshape}")

                print(
                    f"  {lattice:4s} + {mapshape:7s}: "
                    f"shape={matrix.shape}, max={matrix.max()}, symmetric=True"
                )

                # Toroidal maps must never be farther than or equal to planar in
                # shortest-path distance for the same lattice.
                if mapshape == "toroid":
                    planar = create_codebook(mapsize, lattice=lattice, mapshape="planar")
                    planar_matrix = np.vstack([
                        planar.grid_dist(i)
                        for i in range(nnodes)
                    ])
                    require(
                        np.all(matrix <= planar_matrix),
                        f"Toroidal distances exceed planar distances for {lattice}",
                    )

    mark(
        "Codebook.grid_dist",
        "Codebook.toroid_neighborhood",
    )


RUNNER.run("Grid-distance invariants for rect/hexa × planar/toroid", test_grid_distances_all_topologies)

def test_rectangular_squared_euclidean_eight_connected_neighborhood():
    """
    Validate the rectangular SOM topology after switching from Manhattan or
    Chebyshev distance to squared Euclidean grid distance.

    The rectangular lattice remains locally 8-connected, but orthogonal and
    diagonal neighbors are no longer forced to have identical metric values.

    Expected squared grid distances:

        same neuron            -> 0
        orthogonal neighbor    -> 1
        diagonal neighbor      -> 2
        two horizontal steps   -> 4

    A rectangular neuron is considered an immediate 8-neighbor when:

        0 < squared_distance <= 2

    The toroidal case must preserve the same metric after periodic wrapping,
    including wrapped diagonal neighbors with squared distance 2.
    """
    cbm = module("codebook")

    cols, rows = PRIMARY_MAPSIZE

    # --------------------------------------------------------------
    # PLANAR
    # --------------------------------------------------------------
    cb_plan = cbm.Codebook(
        mapsize=(cols, rows),
        lattice="rect",
        mapshape="planar",
        dist_factor=2,
    )

    center_row = rows // 2
    center_col = cols // 2
    center = (
        center_row * cols
        + center_col
    )

    dist_plan = np.asarray(
        cb_plan.grid_dist(center),
        dtype=float,
    )

    expected_plan_neighbors = {
        (
            (center_row + dr) * cols
            + (center_col + dc)
        )
        for dr in (-1, 0, 1)
        for dc in (-1, 0, 1)
        if not (
            dr == 0
            and dc == 0
        )
    }

    actual_plan_neighbors = set(
        np.flatnonzero(
            (dist_plan > 0.0)
            & (dist_plan <= 2.0 + 1e-12)
        ).tolist()
    )

    require(
        actual_plan_neighbors
        == expected_plan_neighbors,
        (
            "Rectangular planar topology is not the expected 8-connected "
            "squared-Euclidean grid. "
            f"Expected {sorted(expected_plan_neighbors)}, "
            f"got {sorted(actual_plan_neighbors)}."
        ),
    )

    require(
        len(actual_plan_neighbors) == 8,
        (
            "An interior rectangular planar neuron must have exactly "
            "8 immediate neighbors under 0 < distance <= 2."
        ),
    )

    right = (
        center_row * cols
        + (center_col + 1)
    )

    down = (
        (center_row + 1) * cols
        + center_col
    )

    diagonal = (
        (center_row + 1) * cols
        + (center_col + 1)
    )

    two_right = (
        center_row * cols
        + (center_col + 2)
    )

    require_close(
        dist_plan[right],
        1.0,
        rtol=0,
        atol=1e-12,
        message="Right orthogonal neighbor must have squared distance 1.",
    )

    require_close(
        dist_plan[down],
        1.0,
        rtol=0,
        atol=1e-12,
        message="Down orthogonal neighbor must have squared distance 1.",
    )

    require_close(
        dist_plan[diagonal],
        2.0,
        rtol=0,
        atol=1e-12,
        message="Diagonal neighbor must have squared distance 2.",
    )

    require_close(
        dist_plan[two_right],
        4.0,
        rtol=0,
        atol=1e-12,
        message="Two horizontal steps must have squared distance 4.",
    )

    # --------------------------------------------------------------
    # TOROID
    # --------------------------------------------------------------
    cb_tor = cbm.Codebook(
        mapsize=(cols, rows),
        lattice="rect",
        mapshape="toroid",
        dist_factor=2,
    )

    corner = 0

    dist_tor = np.asarray(
        cb_tor.grid_dist(corner),
        dtype=float,
    )

    expected_tor_neighbors = {
        (
            (dr % rows) * cols
            + (dc % cols)
        )
        for dr in (-1, 0, 1)
        for dc in (-1, 0, 1)
        if not (
            dr == 0
            and dc == 0
        )
    }

    actual_tor_neighbors = set(
        np.flatnonzero(
            (dist_tor > 0.0)
            & (dist_tor <= 2.0 + 1e-12)
        ).tolist()
    )

    require(
        actual_tor_neighbors
        == expected_tor_neighbors,
        (
            "Rectangular toroidal topology is not 8-connected across "
            "periodic borders using squared Euclidean distance."
        ),
    )

    require(
        len(actual_tor_neighbors) == 8,
        (
            "A rectangular toroidal corner neuron must have exactly "
            "8 immediate wrapped neighbors."
        ),
    )

    wrapped_left = cols - 1
    wrapped_up = (rows - 1) * cols
    wrapped_diagonal = (
        (rows - 1) * cols
        + (cols - 1)
    )

    require_close(
        dist_tor[wrapped_left],
        1.0,
        rtol=0,
        atol=1e-12,
        message="Wrapped horizontal neighbor must have squared distance 1.",
    )

    require_close(
        dist_tor[wrapped_up],
        1.0,
        rtol=0,
        atol=1e-12,
        message="Wrapped vertical neighbor must have squared distance 1.",
    )

    require_close(
        dist_tor[wrapped_diagonal],
        2.0,
        rtol=0,
        atol=1e-12,
        message="Wrapped diagonal neighbor must have squared distance 2.",
    )

    # Symmetry of the new metric.
    for source in (
        0,
        center,
        cols - 1,
        (rows - 1) * cols,
    ):
        d_source = np.asarray(
            cb_tor.grid_dist(source),
            dtype=float,
        )

        for target in (
            0,
            center,
            cols - 1,
            rows * cols - 1,
        ):
            d_target = np.asarray(
                cb_tor.grid_dist(target),
                dtype=float,
            )

            require_close(
                d_source[target],
                d_target[source],
                rtol=0,
                atol=1e-12,
                message=(
                    "Squared-Euclidean rectangular toroidal distance "
                    "must be symmetric."
                ),
            )

    print(
        "Planar immediate 8-neighbors:",
        sorted(actual_plan_neighbors),
    )
    print(
        "Toroidal wrapped 8-neighbors:",
        sorted(actual_tor_neighbors),
    )
    print(
        "Metric check:",
        {
            "orthogonal": float(dist_plan[right]),
            "diagonal": float(dist_plan[diagonal]),
            "two_steps": float(dist_plan[two_right]),
            "wrapped_diagonal": float(dist_tor[wrapped_diagonal]),
        },
    )


RUNNER.run(
    "Rectangular grid uses squared-Euclidean 8-connected topology",
    test_rectangular_squared_euclidean_eight_connected_neighborhood,
)


def test_rectangular_metric_neighborhood_consistency():
    """
    Validate that the squared-Euclidean rectangular grid is consistent with
    the existing Gaussian and Bubble neighborhood implementations.

    GaussianNeighborhood consumes squared distances directly:

        exp(-d_squared / (2 * radius**2))

    BubbleNeighborhood applies sqrt() internally before radius comparison.

    Therefore:
        orthogonal d_squared = 1
        diagonal   d_squared = 2

    must produce an isotropic Euclidean neighborhood rather than square
    Chebyshev bands.
    """
    cbm = module("codebook")
    obj = module("object_functions")

    cols = 5
    rows = 5

    cb = cbm.Codebook(
        mapsize=(cols, rows),
        lattice="rect",
        mapshape="planar",
        dist_factor=2,
    )

    center_row = 2
    center_col = 2
    center = center_row * cols + center_col

    distance_row = np.asarray(
        cb.grid_dist(center),
        dtype=float,
    )

    right = center_row * cols + (center_col + 1)
    diagonal = (center_row + 1) * cols + (center_col + 1)
    two_right = center_row * cols + (center_col + 2)

    gaussian = obj.GaussianNeighborhood()

    gaussian_map = gaussian.calculate(
        distance_row,
        radius=1.0,
        dim=5,
    )

    gaussian_flat = gaussian_map.ravel()

    require_close(
        gaussian_flat[center],
        1.0,
        rtol=0,
        atol=1e-12,
        message="Gaussian BMU influence must equal 1.",
    )

    require_close(
        gaussian_flat[right],
        np.exp(-0.5),
        rtol=1e-12,
        atol=1e-12,
        message="Orthogonal Gaussian influence is inconsistent.",
    )

    require_close(
        gaussian_flat[diagonal],
        np.exp(-1.0),
        rtol=1e-12,
        atol=1e-12,
        message="Diagonal Gaussian influence is inconsistent.",
    )

    require_close(
        gaussian_flat[two_right],
        np.exp(-2.0),
        rtol=1e-12,
        atol=1e-12,
        message="Two-step Gaussian influence is inconsistent.",
    )

    require(
        gaussian_flat[center]
        > gaussian_flat[right]
        > gaussian_flat[diagonal]
        > gaussian_flat[two_right],
        (
            "Gaussian influence should decay monotonically with true "
            "Euclidean grid distance."
        ),
    )

    bubble = obj.BubbleNeighborhood()

    bubble_radius_1 = bubble.calculate(
        distance_row,
        radius=1.0,
        dim=5,
    ).ravel()

    bubble_radius_diag = bubble.calculate(
        distance_row,
        radius=np.sqrt(2.0) + 1e-12,
        dim=5,
    ).ravel()

    # radius=1 includes center + four orthogonal neighbors.
    active_r1 = np.flatnonzero(
        bubble_radius_1 > 0.5
    )

    require(
        len(active_r1) == 5,
        (
            "Bubble radius=1 should include only the BMU plus the "
            "4 orthogonal neighbors."
        ),
    )

    # radius=sqrt(2) includes center + all eight surrounding neighbors.
    active_rdiag = np.flatnonzero(
        bubble_radius_diag > 0.5
    )

    require(
        len(active_rdiag) == 9,
        (
            "Bubble radius=sqrt(2) should include the BMU plus all "
            "8 rectangular neighbors."
        ),
    )

    print(
        "Gaussian influences:",
        {
            "center": float(gaussian_flat[center]),
            "orthogonal": float(gaussian_flat[right]),
            "diagonal": float(gaussian_flat[diagonal]),
            "two_steps": float(gaussian_flat[two_right]),
        },
    )


RUNNER.run(
    "Squared-Euclidean rectangular metric matches Gaussian/Bubble neighborhoods",
    test_rectangular_metric_neighborhood_consistency,
)



