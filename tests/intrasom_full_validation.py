def test_toroid_umatrix_flat_geometry_alignment():
    """
    Regression test for a toroidal flat-U-Matrix artifact.

    Previously, wrap-around neighbor relations were drawn one cell outside
    the fundamental 2-D map domain. On large 15x20 U-Matrices this made
    alternate/interstitial rows look horizontally shifted.

    The ordinary 2-D U-Matrix must contain only edge cells whose neighbor
    relation stays inside the flat domain. Periodic wrap relations remain
    available exclusively to the torus texture renderer.
    """
    viz = module("visualization")

    require(
        "TRAINED_MODELS" in globals(),
        "TRAINED_MODELS cache was not created by the training section.",
    )

    for lattice in ("hexa", "rect"):

        som = TRAINED_MODELS[
            (
                PRIMARY_MAPSIZE,
                lattice,
                "toroid",
            )
        ]

        plotter = viz.PlotFactory(
            som
        )

        um = som.build_umatrix(
            expanded=True
        )
        umat = som.build_umatrix(
            expanded=False
        )

        (
            node_centers,
            _,
            edge_centers,
            edge_values,
        ) = plotter._umatrix_geometry(
            um,
            umat,
            include_toroid_wrap=False,
        )

        valid_edges = edge_centers[
            np.isfinite(edge_values)
        ]

        xmin = np.min(
            node_centers[:, 0]
        )
        xmax = np.max(
            node_centers[:, 0]
        )
        ymin = np.min(
            node_centers[:, 1]
        )
        ymax = np.max(
            node_centers[:, 1]
        )

        require(
            np.all(
                valid_edges[:, 0]
                >= xmin - 1e-12
            ),
            (
                f"{lattice}: flat toroidal U-Matrix has "
                "distance cells protruding beyond the left border."
            ),
        )

        require(
            np.all(
                valid_edges[:, 0]
                <= xmax + 1e-12
            ),
            (
                f"{lattice}: flat toroidal U-Matrix has "
                "distance cells protruding beyond the right border."
            ),
        )

        require(
            np.all(
                valid_edges[:, 1]
                >= ymin - 1e-12
            ),
            (
                f"{lattice}: flat toroidal U-Matrix has "
                "distance cells protruding beyond the top border."
            ),
        )

        require(
            np.all(
                valid_edges[:, 1]
                <= ymax + 1e-12
            ),
            (
                f"{lattice}: flat toroidal U-Matrix has "
                "distance cells protruding beyond the bottom border."
            ),
        )

        # The torus texture path must still retain more/equal periodic edges.
        (
            _,
            _,
            _,
            periodic_edge_values,
        ) = plotter._umatrix_geometry(
            um,
            umat,
            include_toroid_wrap=True,
        )

        require(
            np.count_nonzero(
                np.isfinite(
                    periodic_edge_values
                )
            )
            >=
            np.count_nonzero(
                np.isfinite(
                    edge_values
                )
            ),
            (
                f"{lattice}: periodic torus geometry unexpectedly lost "
                "wrap-around relations."
            ),
        )

        print(
            f"{lattice}: flat edges="
            f"{np.count_nonzero(np.isfinite(edge_values))}, "
            f"periodic edges="
            f"{np.count_nonzero(np.isfinite(periodic_edge_values))}"
        )


RUNNER.run(
    "Toroidal flat U-Matrix has no shifted/protruding alternate rows",
    test_toroid_umatrix_flat_geometry_alignment,
)


