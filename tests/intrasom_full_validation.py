def test_neighborhoods():
    obj = module("object_functions")

    distance = np.arange(16, dtype=float).reshape(4, 4)

    gaussian = obj.NeighborhoodFactory.build("gaussian")
    bubble = obj.NeighborhoodFactory.build("bubble")

    mark(
        "NeighborhoodFactory.build",
        "GaussianNeighborhood.calculate",
        "GaussianNeighborhood.__call__",
        "BubbleNeighborhood.calculate",
        "BubbleNeighborhood.__call__",
    )

    g = gaussian.calculate(distance, radius=2.0, dim=4)
    b = bubble.calculate(distance, radius=2.0, dim=4)

    require_shape(g, (4, 4), "Gaussian neighborhood")
    require_shape(b, (4, 4), "Bubble neighborhood")
    require(np.isfinite(g).all(), "Gaussian contains non-finite values")
    require(np.isfinite(b).all(), "Bubble contains non-finite values")
    require_close(g[0, 0], 1.0, message="Gaussian at zero distance must equal 1")

    # __call__ must forward both positional and keyword arguments to
    # calculate(); this catches regressions in the callable wrapper.
    g_call = gaussian(distance, radius=2.0, dim=4)
    b_call = bubble(distance, radius=2.0, dim=4)
    require_close(g_call, g)
    require_close(b_call, b)

