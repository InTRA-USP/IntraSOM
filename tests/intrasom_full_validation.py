def resolve_animais_datasets():
    """
    Resolve BOTH canonical validation workbooks.

    Preferred structure:

        Tests/
        ├── intrasom_full_validation_animais_mask999_v2.py
        └── data/
            ├── Animais_missing.xlsx
            └── Animais_complete_for_tests.xlsx

    Search roots include both the notebook current directory and the directory
    containing this script, so `%run` works regardless of where Jupyter was
    originally launched.
    """
    explicit_missing = os.environ.get("INTRASOM_TEST_DATA")
    explicit_complete = os.environ.get("INTRASOM_TEST_COMPLETE_DATA")

    if explicit_missing or explicit_complete:
        if not (explicit_missing and explicit_complete):
            raise RuntimeError(
                "When using environment variables, set BOTH "
                "INTRASOM_TEST_DATA and INTRASOM_TEST_COMPLETE_DATA."
            )

        missing_path = Path(explicit_missing).expanduser().resolve()
        complete_path = Path(explicit_complete).expanduser().resolve()

        require(missing_path.exists(), f"Missing workbook not found: {missing_path}")
        require(complete_path.exists(), f"Complete workbook not found: {complete_path}")

        return missing_path, complete_path

    roots = []
    for root in (ORIGINAL_CWD, SCRIPT_DIR):
        root = Path(root).resolve()
        if root not in roots:
            roots.append(root)

    attempted = []

    for root in roots:
        for rel_dir in DATA_DIR_CANDIDATES:
            folder = (root / rel_dir).resolve()

            missing_path = folder / DATASET_MISSING_FILENAME
            complete_path = folder / DATASET_COMPLETE_FILENAME

            attempted.append((missing_path, complete_path))

            if missing_path.exists() and complete_path.exists():
                # Detect accidentally downloaded GitHub HTML previews.
                for candidate in (missing_path, complete_path):
                    with candidate.open("rb") as fh:
                        head = fh.read(4096).lstrip().lower()

                    if b"<!doctype html" in head or b"<html" in head:
                        raise RuntimeError(
                            f"{candidate} is HTML saved with an .xlsx extension, "
                            "not a real Excel workbook."
                        )

                return missing_path, complete_path

    attempted_text = "\n".join(
        f"  missing : {m}\n  complete: {c}"
        for m, c in attempted
    )

    raise FileNotFoundError(
        "Could not find BOTH validation databases in the same data folder.\n\n"
        f"Expected filenames:\n"
        f"  {DATASET_MISSING_FILENAME}\n"
        f"  {DATASET_COMPLETE_FILENAME}\n\n"
        f"Searched:\n{attempted_text}"
    )


def load_animais_missing(path: Path) -> pd.DataFrame:
    """
    Load the canonical Animais dataset while preserving the -999 missing flag.

    The first column contains animal/sample names and becomes the DataFrame
    index. All feature columns must be numerical.

    IMPORTANT:
    This loader intentionally does NOT convert -999 to NaN. Missing-data
    training must explicitly test IntraSOM's public `mask=-999` workflow.
    """
    df = pd.read_excel(
        path,
        sheet_name="Plan1",
        index_col=0,
    )

    df = (
        df
        .dropna(axis=0, how="all")
        .dropna(axis=1, how="all")
    )

    require(
        df.shape[0] >= 2,
        "Animais dataset must contain at least two samples",
    )
    require(
        df.shape[1] >= 2,
        "Animais dataset must contain at least two features",
    )

    converted = {}
    bad_columns = []

    for col in df.columns:
        try:
            converted[col] = pd.to_numeric(
                df[col],
                errors="raise",
            )
        except Exception:
            bad_columns.append(str(col))

    require(
        not bad_columns,
        f"Non-numeric feature columns found: {bad_columns}",
    )

    df = pd.DataFrame(
        converted,
        index=df.index,
    )

    df.index = df.index.map(str)

    require(
        df.index.is_unique,
        "Animais dataset index/sample names must be unique",
    )

    require(
        not df.isna().to_numpy().any(),
        "Unexpected NaN values found. The canonical Animais fixture should "
        "represent missing data with -999.",
    )

    flag_mask = df.eq(MISSING_FLAG)

    require(
        flag_mask.to_numpy().any(),
        f"{DATASET_MISSING_FILENAME} does not contain the expected missing flag "
        f"{MISSING_FLAG}.",
    )

    actual_missing_positions = {
        (str(row_name), str(col_name))
        for row_name, row_values in flag_mask.iterrows()
        for col_name, is_missing in row_values.items()
        if bool(is_missing)
    }

    expected_missing_positions = set(
        KNOWN_COMPLETIONS.keys()
    )

    require(
        actual_missing_positions == expected_missing_positions,
        (
            "Unexpected -999 positions in Animais_missing.xlsx.\n"
            f"Expected: {sorted(expected_missing_positions)}\n"
            f"Found   : {sorted(actual_missing_positions)}"
        ),
    )

    return df


def load_animais_complete(path: Path) -> pd.DataFrame:
    """Load the known complete reference workbook."""
    df = pd.read_excel(
        path,
        sheet_name="Plan1",
        index_col=0,
    )

    df = (
        df
        .dropna(axis=0, how="all")
        .dropna(axis=1, how="all")
    )

    converted = {}

    for col in df.columns:
        converted[col] = pd.to_numeric(
            df[col],
            errors="raise",
        )

    df = pd.DataFrame(
        converted,
        index=df.index,
    )

    df.index = df.index.map(str)

    require(
        not df.isna().to_numpy().any(),
        "Complete validation workbook contains NaN values.",
    )
    require(
        not df.eq(MISSING_FLAG).to_numpy().any(),
        "Complete validation workbook still contains -999 flags.",
    )

    return df


def validate_missing_complete_pair(
    missing_df: pd.DataFrame,
    complete_df: pd.DataFrame,
):
    """
    Validate that the two workbooks are identical except at the canonical
    -999 cells, whose complete values are known.
    """
    require(
        missing_df.shape == complete_df.shape,
        (
            f"Missing/complete shapes differ: "
            f"{missing_df.shape} vs {complete_df.shape}"
        ),
    )

    require(
        list(missing_df.columns) == list(complete_df.columns),
        "Missing/complete column order differs.",
    )

    require(
        list(missing_df.index) == list(complete_df.index),
        "Missing/complete sample index differs.",
    )

    flag_mask = (
        missing_df
        .eq(MISSING_FLAG)
        .to_numpy(copy=True)
    )

    observed_mask = ~flag_mask

    require_close(
        missing_df.to_numpy(dtype=float)[observed_mask],
        complete_df.to_numpy(dtype=float)[observed_mask],
        rtol=0,
        atol=0,
        message=(
            "The complete workbook changes values that were already observed "
            "in the missing workbook."
        ),
    )

    rows = []

    for (sample_name, column_name), expected_value in KNOWN_COMPLETIONS.items():
        missing_value = missing_df.loc[
            sample_name,
            column_name,
        ]

        complete_value = complete_df.loc[
            sample_name,
            column_name,
        ]

        require(
            missing_value == MISSING_FLAG,
            (
                f"Expected {MISSING_FLAG} at "
                f"{sample_name}/{column_name}, found {missing_value!r}."
            ),
        )

        require_close(
            complete_value,
            expected_value,
            rtol=0,
            atol=0,
            message=(
                f"Unexpected complete value at "
                f"{sample_name}/{column_name}"
            ),
        )

        rows.append(
            {
                "sample": sample_name,
                "column": column_name,
                "missing_value": missing_value,
                "complete_value": complete_value,
            }
        )

    return pd.DataFrame(rows)


def make_projection_df(base_df, n=12):
    n = min(int(n), len(base_df))
    projected = base_df.iloc[:n].copy(deep=True)
    projected.index = [f"Projected_{i:03d}" for i in range(n)]

    # Inject deterministic NaNs only for projection/imputation tests.
    if n >= 2 and projected.shape[1] >= 1:
        projected.iat[1, 0] = np.nan
    if n >= 5 and projected.shape[1] >= 3:
        projected.iat[4, 2] = np.nan
    elif n >= 3 and projected.shape[1] >= 2:
        projected.iat[2, 1] = np.nan

    return projected


