def _forced_topographic_error(
    som,
    bmu1_index,
    bmu2_index,
):
    """
    Evaluate SOM.topographic_error using deterministic synthetic BMU pairs.

    The original _find_bmu method is restored before returning.
    """
    n_samples = len(
        som.get_data
    )

    first = np.vstack(
        [
            np.full(
                n_samples,
                bmu1_index,
                dtype=float,
            ),
            np.zeros(
                n_samples,
                dtype=float,
            ),
        ]
    )

    second = np.vstack(
        [
            np.full(
                n_samples,
                bmu2_index,
                dtype=float,
            ),
            np.zeros(
                n_samples,
                dtype=float,
            ),
        ]
    )

    responses = iter(
        [
            first,
            second,
        ]
    )

    original_find_bmu = (
        som._find_bmu
    )

    try:

        som._find_bmu = (
            lambda *args, **kwargs:
            next(responses)
        )

        return float(
            som.topographic_error
        )

    finally:

        som._find_bmu = (
            original_find_bmu
        )


def test_topographic_error_respects_lattice_adjacency():
    """
    Validate adjacency semantics used by topographic_error.

    Rectangular:
        squared distance 1 -> adjacent
        squared distance 2 -> adjacent (diagonal)
        squared distance 4 -> non-adjacent

    Hexagonal:
        grid distance 1 -> adjacent
        distance > 1    -> non-adjacent
    """

    # --------------------------------------------------------------
    # RECTANGULAR
    # --------------------------------------------------------------
    rect = TRAINED_MODELS[
        (
            PRIMARY_MAPSIZE,
            "rect",
            "planar",
        )
    ]

    cols, rows = rect.mapsize

    row = min(
        rows // 2,
        rows - 3,
    )
    col = min(
        cols // 2,
        cols - 3,
    )

    center = (
        row * cols
        + col
    )

    right = (
        row * cols
        + col + 1
    )

    diagonal = (
        (row + 1) * cols
        + col + 1
    )

    two_right = (
        row * cols
        + col + 2
    )

    require_close(
        rect._distance_matrix[
            center,
            right,
        ],
        1.0,
        rtol=0,
        atol=1e-12,
    )

    require_close(
        rect._distance_matrix[
            center,
            diagonal,
        ],
        2.0,
        rtol=0,
        atol=1e-12,
    )

    require_close(
        rect._distance_matrix[
            center,
            two_right,
        ],
        4.0,
        rtol=0,
        atol=1e-12,
    )

    te_right = _forced_topographic_error(
        rect,
        center,
        right,
    )

    te_diagonal = _forced_topographic_error(
        rect,
        center,
        diagonal,
    )

    te_two_steps = _forced_topographic_error(
        rect,
        center,
        two_right,
    )

    require_close(
        te_right,
        0.0,
        rtol=0,
        atol=1e-12,
        message=(
            "Orthogonal rectangular BMUs must be topological neighbors."
        ),
    )

    require_close(
        te_diagonal,
        0.0,
        rtol=0,
        atol=1e-12,
        message=(
            "Diagonal rectangular BMUs must be topological neighbors."
        ),
    )

    require_close(
        te_two_steps,
        1.0,
        rtol=0,
        atol=1e-12,
        message=(
            "Rectangular BMUs two cells apart must not be immediate neighbors."
        ),
    )

    # --------------------------------------------------------------
    # HEXAGONAL
    # --------------------------------------------------------------
    hexa = TRAINED_MODELS[
        (
            PRIMARY_MAPSIZE,
            "hexa",
            "planar",
        )
    ]

    source = (
        hexa.mapsize[0]
        + 1
    )

    source_dist = (
        hexa._distance_matrix[
            source
        ]
    )

    hexa_neighbor_candidates = np.flatnonzero(
        np.isclose(
            source_dist,
            1.0,
        )
    )

    hexa_far_candidates = np.flatnonzero(
        source_dist > 1.0 + 1e-12
    )

    require(
        hexa_neighbor_candidates.size > 0,
        "Could not identify a hexagonal immediate neighbor.",
    )

    require(
        hexa_far_candidates.size > 0,
        "Could not identify a non-neighboring hexagonal neuron.",
    )

    hexa_neighbor = int(
        hexa_neighbor_candidates[0]
    )

    hexa_far = int(
        hexa_far_candidates[0]
    )

    require_close(
        _forced_topographic_error(
            hexa,
            source,
            hexa_neighbor,
        ),
        0.0,
        rtol=0,
        atol=1e-12,
        message=(
            "Hexagonal distance-1 BMUs must be topological neighbors."
        ),
    )

    require_close(
        _forced_topographic_error(
            hexa,
            source,
            hexa_far,
        ),
        1.0,
        rtol=0,
        atol=1e-12,
        message=(
            "Hexagonal BMUs beyond distance 1 must not be immediate neighbors."
        ),
    )

    print(
        "Forced topographic errors:",
        {
            "rect_orthogonal": te_right,
            "rect_diagonal": te_diagonal,
            "rect_two_steps": te_two_steps,
        },
    )


RUNNER.run(
    "Topographic error respects rect-8 and hexa-6 adjacency",
    test_topographic_error_respects_lattice_adjacency,
)


def test_training_organization_diagnostics():
    """
    Non-destructive convergence diagnostics for the trained validation maps.

    A converged SOM should generally place more similar codebook vectors near
    each other than arbitrary pairs. The test compares the mean feature-space
    distance of immediate topological neighbors with the mean distance across
    all neuron pairs.

    This is a structural convergence diagnostic, not a mathematical guarantee,
    so it is run as non-critical.
    """
    rows_out = []

    for (
        mapsize,
        lattice,
        mapshape,
    ), som in TRAINED_MODELS.items():

        codebook = np.asarray(
            som.codebook.matrix,
            dtype=float,
        )

        topo = np.asarray(
            som._distance_matrix,
            dtype=float,
        )

        if lattice == "rect":
            adjacency = (
                (topo > 0.0)
                & (topo <= 2.0 + 1e-12)
            )
        else:
            adjacency = np.isclose(
                topo,
                1.0,
            )

        upper = np.triu(
            np.ones_like(
                adjacency,
                dtype=bool,
            ),
            k=1,
        )

        adjacent_pairs = np.argwhere(
            adjacency
            & upper
        )

        all_pairs = np.argwhere(
            upper
        )

        require(
            adjacent_pairs.shape[0] > 0,
            f"No adjacent pairs found for {lattice}/{mapshape}.",
        )

        local_delta = (
            codebook[
                adjacent_pairs[:, 0]
            ]
            - codebook[
                adjacent_pairs[:, 1]
            ]
        )

        local_mean = float(
            np.mean(
                np.linalg.norm(
                    local_delta,
                    axis=1,
                )
            )
        )

        # Deterministic subsample for the global comparison.
        rng = np.random.default_rng(
            RANDOM_SEED
        )

        sample_count = min(
            5000,
            all_pairs.shape[0],
        )

        selected = rng.choice(
            all_pairs.shape[0],
            size=sample_count,
            replace=False,
        )

        sampled_pairs = (
            all_pairs[
                selected
            ]
        )

        global_delta = (
            codebook[
                sampled_pairs[:, 0]
            ]
            - codebook[
                sampled_pairs[:, 1]
            ]
        )

        global_mean = float(
            np.mean(
                np.linalg.norm(
                    global_delta,
                    axis=1,
                )
            )
        )

        ratio = (
            local_mean
            / global_mean
            if global_mean > 0
            else np.nan
        )

        occupied = int(
            np.unique(
                som._bmu[0].astype(int)
            ).size
        )

        rows_out.append(
            {
                "mapsize": str(mapsize),
                "lattice": lattice,
                "mapshape": mapshape,
                "QE": float(som.QE),
                "TE": float(som.topographic_error),
                "occupied_BMUs": occupied,
                "local_neighbor_distance": local_mean,
                "global_pair_distance": global_mean,
                "local/global_ratio": ratio,
            }
        )

        require(
            np.isfinite(ratio),
            (
                f"Non-finite convergence ratio for "
                f"{mapsize}/{lattice}/{mapshape}."
            ),
        )

        require(
            local_mean
            <= global_mean * 1.10,
            (
                "Local codebook vectors are not sufficiently smoother than "
                f"global pairs for {mapsize}/{lattice}/{mapshape}. "
                f"local/global={ratio:.3f}"
            ),
        )

    diagnostics = pd.DataFrame(
        rows_out
    )

    print(
        "\nTraining organization diagnostics:"
    )

    display(
        diagnostics
    )


RUNNER.run(
    "Training organization/convergence diagnostics",
    test_training_organization_diagnostics,
    critical=False,
)


