def training_profile(
    lattice,
    mapsize,
):
    """
    Return a lattice-specific training schedule.

    Rectangular maps use more epochs and a broader initial radius because the
    squared-Euclidean 8-connected topology benefits from a longer ordering
    phase.

    Hexagonal maps already converge relatively well, so they use a lighter
    schedule while still receiving substantially more training than the old
    one-epoch smoke test.
    """
    max_dim = float(
        max(mapsize)
    )

    if lattice == "rect":

        return {
            "rough_epochs": RECT_ROUGH_EPOCHS,
            "fine_epochs": RECT_FINE_EPOCHS,
            "rough_radiusin": max(
                4.0,
                max_dim * 0.30,
            ),
            "rough_radiusfin": 2.5,
            "fine_radiusin": 2.5,
            "fine_radiusfin": 1.0,
        }

    if lattice == "hexa":

        return {
            "rough_epochs": HEXA_ROUGH_EPOCHS,
            "fine_epochs": HEXA_FINE_EPOCHS,
            "rough_radiusin": max(
                3.0,
                max_dim * 0.25,
            ),
            "rough_radiusfin": 2.0,
            "fine_radiusin": 2.0,
            "fine_radiusfin": 1.0,
        }

    raise ValueError(
        f"Unsupported lattice {lattice!r}."
    )


