class ValidationRunner:
    def __init__(self):
        self.results = []
        self.warnings = []
        self.start_time = time.perf_counter()

    def section(self, title: str):
        print("\n" + "=" * 92)
        print(title)
        print("=" * 92)

    def run(self, name: str, func: Callable, *, critical: bool = True):
        print(f"\n▶ {name}")
        started = time.perf_counter()
        try:
            result = func()
        except Exception as exc:
            elapsed = time.perf_counter() - started
            self.results.append((name, False, elapsed, exc, critical))
            print(f"  ❌ FAIL [{elapsed:.3f}s]")
            print(f"     {type(exc).__name__}: {exc}")
            print("     Traceback:")
            tb = traceback.format_exc().rstrip().splitlines()
            for line in tb[-12:]:
                print("       " + line)
            return None
        else:
            elapsed = time.perf_counter() - started
            self.results.append((name, True, elapsed, None, critical))
            print(f"  ✅ PASS [{elapsed:.3f}s]")
            return result

    def warn(self, message: str):
        self.warnings.append(message)
        print(f"  ⚠️  WARN: {message}")

    def summary(self):
        elapsed = time.perf_counter() - self.start_time
        passed = sum(ok for _, ok, *_ in self.results)
        failed = len(self.results) - passed
        critical_failed = sum(
            1 for _, ok, _, _, critical in self.results
            if (not ok and critical)
        )

        self.section("FINAL SUMMARY")
        print(f"Tests executed : {len(self.results)}")
        print(f"Passed         : {passed}")
        print(f"Failed         : {failed}")
        print(f"Critical fails : {critical_failed}")
        print(f"Warnings       : {len(self.warnings)}")
        print(f"Total time     : {elapsed:.2f}s")

        if failed:
            print("\nFailed tests:")
            for name, ok, _, exc, critical in self.results:
                if not ok:
                    prefix = "CRITICAL" if critical else "NON-CRITICAL"
                    print(f"  - [{prefix}] {name}: {type(exc).__name__}: {exc}")

        if self.warnings:
            print("\nWarnings:")
            for message in self.warnings:
                print(f"  - {message}")

        print("\nResult:")
        if critical_failed == 0:
            print("  ✅ No critical regression detected.")
        else:
            print("  ❌ Critical regressions were detected. Review failures above.")

        return critical_failed


