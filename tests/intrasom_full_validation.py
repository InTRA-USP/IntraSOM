"""
IntraSOM full validation suite for Jupyter Notebook
===================================================

Purpose
-------
Run this script after any update to the IntraSOM source code.
It performs numerical checks, geometry checks, training smoke tests,
missing-data tests, persistence checks, clustering checks, and visual
checks with visible plots.

The suite intentionally DOES NOT test `nonsupervised_eval.py`, because that
module is currently being left for a later review.

Recommended Jupyter usage
-------------------------
From the repository root, with the editable environment activated:

    %run intrasom_full_validation.py

Or:

    import runpy
    runpy.run_path("intrasom_full_validation.py")

The script continues after failures, prints PASS/FAIL/WARN for every section,
and prints a final summary.

Conventions validated throughout
--------------------------------
Public map convention:
    mapsize = (columns, rows)

NumPy 2-D convention:
    shape = (rows, columns)

Linear neuron indexing:
    row = index // columns
    col = index % columns
    index = row * columns + col

Notes
-----
- The suite uses the real `Animais_missing.xlsx` example dataset, where -999 is the missing-data flag.
- A complete copy is generated by replacing only the canonical -999 flags with the known original values.
- Large maps are exercised to expose row/column and plotting regressions: (15,20), (20,15), and (15,15).
- All planar/toroidal and hexa/rect combinations are exercised on the primary large map.
- PlotFactory is tested for both lattice types.
- Legacy SOM.plot_umatrix is tested only as a smoke test because PlotFactory is
  the canonical visualization layer.
- Some slower tests can be disabled in the CONFIG section.
"""

